#pragma once
#include <torch/torch.h>

namespace mapping_cuda {
enum class SelectorForwardBackend { Legacy, Tiled };
enum class SelectorBackwardBackend { Legacy, FusedVJP };
struct SelectorExecutionPlan {
  SelectorForwardBackend forward;
  SelectorBackwardBackend backward;
  bool reusable_compaction;
  bool supported() const { return forward != SelectorForwardBackend::Legacy; }
};
// Offline calibration: RTX3090/sm86, FP32 without TF32, N=1024..1048576.
// Unmeasured devices/populations retain the complete Mapper fallback.
struct SelectorExecutionDispatcher {
  static SelectorExecutionPlan plan(int64_t population, int device);
};
torch::Tensor flexgsInput11(const torch::Tensor& xyz,const torch::Tensor& scale,
    const torch::Tensor& dc,const torch::Tensor& opacity,const torch::Tensor& owner,
    const torch::Tensor& centers,const torch::Tensor& reference,double ratio);
// Supports input widths 11, 19 and 21. Outputs: raw Nx2 logits, first-layer Nx32 shared encoding.
std::vector<torch::Tensor> flexgsMLP(const torch::Tensor& input,const torch::Tensor& w0,
    const torch::Tensor& b0,const torch::Tensor& w1,const torch::Tensor& b1,
    const torch::Tensor& w2,const torch::Tensor& b2);
// Exponentials are generated by ATen so the original RNG stream is retained.
// Outputs: masked deterministic keep probability, hard-ST mask, ascending IDs.
std::vector<torch::Tensor> flexgsSampleCompact(const torch::Tensor& logits,
    const torch::Tensor& exponentials,const torch::Tensor& eligible,double tau);
// Additional unmasked noisy softmax; its VJP retains the original ATen reduction order.
std::vector<torch::Tensor> flexgsSampleCompactWithWeights(const torch::Tensor& logits,
    const torch::Tensor& exponentials,const torch::Tensor& eligible,double tau);
std::vector<torch::Tensor> flexgsInputForward(const std::vector<torch::Tensor>& a,double ratio);
std::vector<torch::Tensor> flexgsInputBackward(const std::vector<torch::Tensor>& a,const torch::Tensor& g);
std::vector<torch::Tensor> flexgsMLPForward(const std::vector<torch::Tensor>& a);
std::vector<torch::Tensor> flexgsMLPBackward(const std::vector<torch::Tensor>& a,
    const torch::Tensor& logits_gradient,const torch::Tensor& shared_gradient);
std::vector<torch::Tensor> flexgsSampleForward(const torch::Tensor& logits,
    const torch::Tensor& exponentials,const torch::Tensor& eligible,double tau);
torch::Tensor flexgsSampleBackward(const std::vector<torch::Tensor>& saved,
    const torch::Tensor& probability_gradient,const torch::Tensor& mask_gradient,double tau);
}
